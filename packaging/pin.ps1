<#
.SYNOPSIS
    Regenerates packaging\requirements.txt: the build environment with exact versions and file checksums.

.DESCRIPTION
    Takes the hand-chosen packages of packaging\requirements.in, resolves everything they need to the versions
    recorded in uv.lock, and writes each one with the checksums of its files. Run it after changing a version
    in requirements.in or in uv.lock:  powershell -ExecutionPolicy Bypass -File packaging\pin.ps1
#>
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
New-Item -ItemType Directory -Force build | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding $false

# the versions of the project environment; its PyTorch pin is the CUDA build, which the CPU-only build replaces
uv export --no-dev --extra desktop --format requirements-txt --no-hashes --no-emit-project --quiet -o build\lock-pins.txt
if ($LASTEXITCODE -ne 0) { throw "uv.lock could not be read." }
$pins = Get-Content build\lock-pins.txt | Where-Object { $_ -notmatch '^torch==' }
[System.IO.File]::WriteAllLines((Join-Path $root "build\lock-pins.txt"), $pins, $utf8)

# hf-xet is a download helper of the model hub library; the application never downloads, so it is left out
uv pip compile packaging\requirements.in -c build\lock-pins.txt -o build\requirements.compiled.txt `
    --generate-hashes --emit-index-url --no-emit-package hf-xet --no-header --quiet `
    --python-version 3.12 --python-platform x86_64-pc-windows-msvc `
    --extra-index-url https://download.pytorch.org/whl/cpu --index-strategy unsafe-best-match
if ($LASTEXITCODE -ne 0) { throw "The packages could not be resolved." }

$header = @(
    "# Build environment of the desktop application: every package pinned to an exact version and file checksum.",
    "# Generated by packaging\pin.ps1 from requirements.in and uv.lock; do not edit by hand.",
    "#",
    "# Install with (packaging\build.ps1 does this):",
    "#   uv pip install --no-deps --require-hashes --index-strategy unsafe-best-match -r packaging\requirements.txt",
    ""
)
$body = Get-Content build\requirements.compiled.txt | Where-Object { $_ -notmatch 'lock-pins\.txt' }
[System.IO.File]::WriteAllText((Join-Path $root "packaging\requirements.txt"), (($header + $body) -join "`n") + "`n", $utf8)
$count = @($body | Where-Object { $_ -match '^[A-Za-z0-9][A-Za-z0-9._-]*==' }).Count
Write-Host "Wrote packaging\requirements.txt ($count packages)."
